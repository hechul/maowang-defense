export function getNpcSideStories(npcId: NpcId): NpcSideStory[] {
  return NPC_SIDE_STORIES.filter((s) => s.npcId === npcId).sort((a, b) => a.index - b.index);
}

export function unlockedSideStories(npcId: NpcId, affinity: number): NpcSideStory[] {
  return getNpcSideStories(npcId).filter((s) => affinity >= s.unlockAffinity);
}
